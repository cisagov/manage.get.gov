"""This module provides a simple logging context mechanism using Python's contextvars.
It allows you to set and retrieve user-specific information that can be included
without having to pass this information explicitly through function parameters."""

from contextvars import ContextVar
from contextlib import contextmanager
from functools import wraps
from types import FunctionType

user_email_var = ContextVar("user_email")  # type: ignore
ip_address_var = ContextVar("ip_address")  # type: ignore
request_path_var = ContextVar("request_path")  # type: ignore
request_id_var = ContextVar("request_id")  # type: ignore
domain_name_var = ContextVar("domain_name")  # type: ignore


def set_user_log_context(user_email=None, ip_address=None, request_path=None, request_id=None):
    if user_email is not None:
        user_email_var.set(user_email)
    if ip_address is not None:
        ip_address_var.set(ip_address)
    if request_path is not None:
        request_path_var.set(request_path)
    if request_id is not None:
        request_id_var.set(request_id)


@contextmanager
def set_domain_log_context(domain_name):
    """
    Attach domain_name to every log line emitted inside this block for classmethods.

    Use as `with set_domain_log_context(domain_name)` as needed.
    """
    token = domain_name_var.set(domain_name)
    try:
        yield
    finally:
        domain_name_var.reset(token)


def get_user_log_context():
    return {
        "user_email": user_email_var.get(None) or "Anonymous",
        "ip_address": ip_address_var.get(None) or "Unknown IP",
        "request_path": request_path_var.get(None),
        "request_id": request_id_var.get(None),
        "domain_name": domain_name_var.get(None),
    }


def clear_user_log_context():
    user_email_var.set(None)
    ip_address_var.set(None)
    request_path_var.set(None)
    request_id_var.set(None)


def set_domain_log_context_for_class(cls):
    """
    Class decorator: tag every log line generated by a model's instance
    methods and properties with that instance's domain name.

    Classmethods, staticmethods, cached_property are left alone. 
    Classmethods need `with set_domain_log_context(domain):` by hand.
    """
    def wrap(func):        
        # This is more for me, since I was new to @wraps. It copies the function's
        # name, docstring, and attributes onto the wrapper. Without it, every method 
        # on Domain would show up as "wrapper" in tracebacks and logs. I believe
        # django-fsm's transition metadeta would also be lost.
        @wraps(func)
        def wrapper(self, *args, **kwargs):
            name = self.__dict__.get("name")
            # If there's no domain name, leave the method alone
            if not name:
                return func(self, *args, **kwargs)
            # Otherwise, add domain name to the logs.
            with set_domain_log_context(name.lower()):
                return func(self, *args, **kwargs)

            return wrapper
    
    for attr, value in list(vars(cls).items()):
        # leave __init__, __str__, etc alone.
        if attr.startswith("__"):
            continue

        if isinstance(value, FunctionType):
            setattr(cls, attr, wrap(value))
        elif isinstance(value, property):
            # We need to handle properties so that they get, set, or delete as needed
            # Note we don't currently have a deleter. Maybe we'd want that wrapped too?
            setattr(
                cls,
                attr,
                # type(value) rather than property so that subclasses like Domain.Cache
                # keep their behavior
                type(value)(
                    wrap(value.fget) if value.fget else None,
                    wrap(value.fset) if value.fset else None,
                    value.fdel,
                ),
            )
    return cls